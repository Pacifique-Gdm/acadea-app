const { buildSync } = require("esbuild");
const { readFileSync, writeFileSync } = require("node:fs");
const { resolve } = require("node:path");

const output = resolve(__dirname, "../api/_lib/timetableValidationBundle.js");
const source = [
  'export { validateTimetable } from "./src/modules/studies/scheduleValidation.ts";',
  'export { logicalStudyClasses } from "./src/modules/studies/studyCourseGroups.ts";',
  'export { studyClassSection } from "./src/modules/studies/studyScope.ts";',
  'export { userSectionIds } from "./src/utils/userSections.ts";',
  'export { resolveAttendanceSchoolDays } from "./src/utils/attendance.ts";',
].join("\n");

const result = buildSync({
  stdin: { contents: source, resolveDir: resolve(__dirname, ".."), sourcefile: "timetable-validation-entry.ts", loader: "ts" },
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  write: false,
  legalComments: "none",
});
const contents = "// Generated by scripts/generateTimetableValidationBundle.cjs; do not edit.\n" + result.outputFiles[0].text;
if (process.argv.includes("--check")) {
  if (readFileSync(output, "utf8") !== contents) {
    console.error("Le bundle de validation des horaires n'est pas synchronisé avec les sources TypeScript.");
    process.exitCode = 1;
  }
} else {
  writeFileSync(output, contents);
}
